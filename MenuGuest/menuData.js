// ---------- Product modal details ----------
// Stable per-item details used by the product modal. Ratings and total sold
// are derived from each item's popularity plus a hash of its id, so every
// item keeps the same numbers across renders and visits.
const hashId = (id) => {
  let hash = 0;
  for (let index = 0; index < id.length; index += 1) {
    hash = (hash * 31 + id.charCodeAt(index)) % 9973;
  }
  return hash;
};

export const getItemRating = (item) =>
  (
    4.3 +
    (item.popularity - 7) * 0.2 +
    ((hashId(item.id) % 5) / 10 - 0.2)
  ).toFixed(1);

export const getItemSold = (item) =>
  150 + item.popularity * 85 + (hashId(item.id) % 50) * 12;

