// ---------- Product modal option choices ----------
// "single" groups behave like radios (first choice is the default unless
// defaultId says otherwise); "multi" groups behave like checkboxes. A choice
// with a price adds to the item price; choices without a price are free.
const choiceGroup = (id, label, options, type = "single") => ({
  id,
  label,
  type,
  choices: options.map((option) =>
    typeof option === "string" ? { id: option, label: option } : option,
  ),
});

